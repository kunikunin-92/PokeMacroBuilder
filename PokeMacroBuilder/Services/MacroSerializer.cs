using System;
using System.Collections.Generic;
using System.Collections.ObjectModel;
using System.Linq;
using System.Text;
using System.Text.Json;
using PokeMacroBuilder.Models;

namespace PokeMacroBuilder.Services;

// ---- 永続化用 DTO ----
internal sealed class MacroDto
{
    public int Version { get; set; } = 2;
    public string DisplayName { get; set; } = "";
    public string Loop { get; set; } = "None";
    public int LoopCount { get; set; } = 1;
    public List<BlockDto> Blocks { get; set; } = new();
}

internal sealed class BlockDto
{
    public string Kind { get; set; } = "";
    // 入力
    public List<string>? Keys { get; set; }
    public double Duration { get; set; }
    public double Wait { get; set; }
    public int Repeat { get; set; } = 1;
    public double Seconds { get; set; }
    public int Device { get; set; }
    public int Direction { get; set; }
    public double Magnitude { get; set; } = 100;
    public int Mode { get; set; }
    public string? KeyCode { get; set; }
    // 制御
    public int Count { get; set; } = 10;
    public string CondVar { get; set; } = "cnt";
    public int CondOp { get; set; }
    public string CondValue { get; set; } = "0";
    public bool HasElse { get; set; }
    public List<BlockDto>? Children { get; set; }
    public List<BlockDto>? ElseChildren { get; set; }
    // 変数・通知
    public string VarName { get; set; } = "cnt";
    public int VarOp { get; set; }
    public string VarValue { get; set; } = "0";
    public int Channel { get; set; }
    public string Text { get; set; } = "";
    public string Name { get; set; } = "";
}

/// <summary>
/// MacroDocument と JSON(Base64) の相互変換。
/// 生成 .py の先頭コメント「# PMB-DATA:&lt;base64&gt;」に保存し、再読み込み時に復元する。
/// </summary>
public static class MacroSerializer
{
    public const string Marker = "# PMB-DATA:";
    public const string SignatureComment = "# Generated by PokeMacroBuilder";

    private static readonly JsonSerializerOptions JsonOpts = new() { WriteIndented = false };

    public static string ToBase64(MacroDocument doc)
    {
        var dto = new MacroDto
        {
            DisplayName = doc.DisplayName,
            Loop = doc.Loop.ToString(),
            LoopCount = doc.LoopCount,
            Blocks = doc.Blocks.Select(BuildBlock).ToList(),
        };
        var json = JsonSerializer.Serialize(dto, JsonOpts);
        return Convert.ToBase64String(Encoding.UTF8.GetBytes(json));
    }

    public static MacroDocument Clone(MacroDocument doc)
        => TryParse(Marker + ToBase64(doc)) ?? new MacroDocument { DisplayName = doc.DisplayName };

    public static MacroDocument? TryParse(string fileText)
    {
        string? base64 = null;
        foreach (var rawLine in fileText.Split('\n'))
        {
            var line = rawLine.Trim();
            if (line.StartsWith(Marker, StringComparison.Ordinal))
            {
                base64 = line.Substring(Marker.Length).Trim();
                break;
            }
        }
        if (string.IsNullOrEmpty(base64)) return null;

        try
        {
            var json = Encoding.UTF8.GetString(Convert.FromBase64String(base64));
            var dto = JsonSerializer.Deserialize<MacroDto>(json, JsonOpts);
            if (dto is null) return null;

            var doc = new MacroDocument
            {
                DisplayName = dto.DisplayName,
                Loop = Enum.TryParse<LoopMode>(dto.Loop, out var lm) ? lm : LoopMode.None,
                LoopCount = dto.LoopCount <= 0 ? 1 : dto.LoopCount,
            };
            foreach (var b in dto.Blocks) doc.Blocks.Add(BuildModel(b));
            return doc;
        }
        catch
        {
            return null;
        }
    }

    // ---- model -> dto ----
    private static BlockDto BuildBlock(MacroBlock b)
    {
        switch (b)
        {
            case PressBlock p:
                return new BlockDto
                {
                    Kind = "press",
                    Keys = p.Keys.Select(k => k.SelectedKey.Code).ToList(),
                    Duration = p.Duration, Wait = p.Wait, Repeat = p.Repeat,
                };
            case StickBlock s:
                return new BlockDto
                {
                    Kind = "stick", Device = s.Device, Direction = s.Direction,
                    Magnitude = s.Magnitude, Duration = s.Duration, Wait = s.Wait,
                };
            case HoldBlock h:
                return new BlockDto { Kind = "hold", Mode = h.Mode, KeyCode = h.Key.SelectedKey.Code, Wait = h.Wait };
            case WaitBlock w:
                return new BlockDto { Kind = "wait", Seconds = w.Seconds };
            case RepeatBlock r:
                return new BlockDto { Kind = "repeat", Count = r.Count, Children = r.Children.Select(BuildBlock).ToList() };
            case ForeverBlock f:
                return new BlockDto { Kind = "forever", Children = f.Children.Select(BuildBlock).ToList() };
            case WhileBlock wb:
                return new BlockDto
                {
                    Kind = "while",
                    CondVar = wb.Condition.Var, CondOp = wb.Condition.Op, CondValue = wb.Condition.Value,
                    Children = wb.Children.Select(BuildBlock).ToList(),
                };
            case IfBlock ib:
                return new BlockDto
                {
                    Kind = "if",
                    CondVar = ib.Condition.Var, CondOp = ib.Condition.Op, CondValue = ib.Condition.Value,
                    HasElse = ib.HasElse,
                    Children = ib.Children.Select(BuildBlock).ToList(),
                    ElseChildren = ib.ElseChildren.Select(BuildBlock).ToList(),
                };
            case VariableBlock v:
                return new BlockDto { Kind = "var", VarName = v.Name, VarOp = v.Op, VarValue = v.Value };
            case LogBlock l:
                return new BlockDto { Kind = "log", Text = l.Text };
            case NotifyBlock n:
                return new BlockDto { Kind = "notify", Channel = n.Channel, Text = n.Text };
            case ScreenshotBlock sc:
                return new BlockDto { Kind = "screenshot", Name = sc.Name };
            default:
                return new BlockDto { Kind = "wait", Seconds = 0 };
        }
    }

    // ---- dto -> model ----
    private static MacroBlock BuildModel(BlockDto b)
    {
        switch (b.Kind)
        {
            case "press":
                var pb = new PressBlock { Duration = b.Duration, Wait = b.Wait, Repeat = b.Repeat < 1 ? 1 : b.Repeat };
                pb.Keys.Clear();
                if (b.Keys is { Count: > 0 })
                    foreach (var c in b.Keys) pb.Keys.Add(new KeySlot { SelectedKey = KeyCatalog.FromCode(c) });
                else pb.Keys.Add(new KeySlot());
                return pb;
            case "stick":
                return new StickBlock
                {
                    Device = b.Device is >= 0 and <= 2 ? b.Device : 1,
                    Direction = b.Direction is >= 0 and < 8 ? b.Direction : 0,
                    Magnitude = b.Magnitude is > 0 and <= 100 ? b.Magnitude : 100,
                    Duration = b.Duration, Wait = b.Wait,
                };
            case "hold":
                var hb = new HoldBlock { Mode = b.Mode == 1 ? 1 : 0, Wait = b.Wait };
                hb.Key.SelectedKey = KeyCatalog.FromCode(b.KeyCode);
                return hb;
            case "repeat":
                var rb = new RepeatBlock { Count = b.Count };
                Fill(rb.Children, b.Children);
                return rb;
            case "forever":
                var fb = new ForeverBlock();
                Fill(fb.Children, b.Children);
                return fb;
            case "while":
                var wbk = new WhileBlock();
                wbk.Condition.Var = b.CondVar; wbk.Condition.Op = b.CondOp; wbk.Condition.Value = b.CondValue;
                Fill(wbk.Children, b.Children);
                return wbk;
            case "if":
                var ifb = new IfBlock { HasElse = b.HasElse };
                ifb.Condition.Var = b.CondVar; ifb.Condition.Op = b.CondOp; ifb.Condition.Value = b.CondValue;
                Fill(ifb.Children, b.Children);
                Fill(ifb.ElseChildren, b.ElseChildren);
                return ifb;
            case "var":
                return new VariableBlock { Name = b.VarName, Op = b.VarOp == 1 ? 1 : 0, Value = b.VarValue };
            case "log":
                return new LogBlock { Text = b.Text };
            case "notify":
                return new NotifyBlock { Channel = b.Channel == 1 ? 1 : 0, Text = b.Text };
            case "screenshot":
                return new ScreenshotBlock { Name = b.Name };
            default:
                return new WaitBlock { Seconds = b.Seconds };
        }
    }

    private static void Fill(ObservableCollection<MacroBlock> dest, List<BlockDto>? src)
    {
        if (src is null) return;
        foreach (var c in src) dest.Add(BuildModel(c));
    }
}
